def _upgrade_offline_static() -> None:
    # Offline (--sql) rendering has no live database to reflect, but the
    # script it produces must still be complete (M-04). On any database built
    # by running this chain in order, none of these tables/columns exist yet,
    # so emit the full additive changeset unconditionally.

    # 1. Missing tables (parents before children).
    for table_name in (
        "marketing_campaigns",
        "marketing_templates",
        "marketing_campaign_segments",
        "marketing_emails",
        "newsletter_subscriptions",
    ):
        _NEW_TABLES[table_name]()

    # 2. Added columns (plain ALTER TABLE; batch mode needs reflection,
    #    which offline mode lacks).
    for table_name, columns in _ADDED_COLUMNS.items():
        for _col_name, column in columns:
            op.add_column(table_name, column)


def upgrade() -> None:
    bind = op.get_bind()
    if _inspect_safe(bind) is None:
        _upgrade_offline_static()
        return

    # 1. Missing tables (parents before children).
    for table_name in (
        "marketing_campaigns",
        "marketing_templates",
        "marketing_campaign_segments",
        "marketing_emails",
        "newsletter_subscriptions",
    ):
        if not _table_exists(bind, table_name):
            _NEW_TABLES[table_name]()
            logger.info("c7d8e9f0a1b2: created missing table %s", table_name)

    # 2. Missing columns on existing tables.
    for table_name, columns in _ADDED_COLUMNS.items():
        if not _table_exists(bind, table_name):
            logger.warning(
                "c7d8e9f0a1b2: table %s does not exist; skipping column adds",
                table_name,
            )
            continue
        present = _columns(bind, table_name)
        with op.batch_alter_table(table_name, schema=None) as batch_op:
            for col_name, column in columns:
                if col_name in present:
                    continue  # idempotent re-run
                batch_op.add_column(column)
                logger.info(
                    "c7d8e9f0a1b2: added %s.%s", table_name, col_name
                )


def downgrade() -> None:
    bind = op.get_bind()
    if _inspect_safe(bind) is None:
        logger.warning(
            "c7d8e9f0a1b2 downgrade: reflection unavailable; emitting no DDL"
        )
        return

    # Downgrade only removes what this revision created; added columns are
    # kept on downgrade (they may hold data written since upgrade).
    for table_name in reversed(list(_NEW_TABLES)):
        if _table_exists(bind, table_name):
            op.drop_table(table_name)
